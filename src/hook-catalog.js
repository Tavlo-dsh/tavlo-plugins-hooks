const MOUNT_POINT_MAP = new Map(HOOK_MOUNT_POINTS.map((mp) => [mp.id, mp]))

/**
 * Look up a hook mount point definition by id.
 * @param {string} id
 */
export function getMountPoint(id) {
  return typeof id === 'string' ? MOUNT_POINT_MAP.get(id) : undefined
}

/**
 * Build default 6-category subscription map from CATEGORY_META.
 */
export function createDefaultCategoryEvents() {
  const out = {}
  for (const cat of NOTIFICATION_CATEGORIES) {
    out[cat] = Boolean(CATEGORY_META[cat]?.defaultSelected)
  }
  return out
}
