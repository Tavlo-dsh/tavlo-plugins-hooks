import { build, transform } from 'esbuild'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
const read = (relPath) => readFile(resolve(root, relPath), 'utf8')

const pkg = JSON.parse(await read('package.json'))
const runtimeModules = new Set([
  'react',
  'react/jsx-runtime',
  'react-dom',
  'react-dom/client',
  '@deepseek-ai/dsh-client-ui-primitives',
])

const result = await build({
  absWorkingDir: root,
  entryPoints: ['src/client/index.tsx'],
  outdir: 'lib',
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2020',
  jsx: 'automatic',
  external: [...runtimeModules],
  define: {
    'process.env.NODE_ENV': '"production"',
  },
  metafile: true,
  write: false,
  minifySyntax: true,
  minifyWhitespace: true,
  legalComments: 'inline',
})

const jsFile = result.outputFiles.find((file) => file.path.endsWith('.js'))
const cssFile = result.outputFiles.find((file) => file.path.endsWith('.css'))

if (!jsFile) {
  throw new Error('Expected esbuild to emit a JS bundle output')
}

for (const output of Object.values(result.metafile.outputs)) {
  for (const entry of output.imports) {
    if (entry.external && !runtimeModules.has(entry.path)) {
      throw new Error(`Unsupported external client import: ${entry.path}`)
    }
  }
}

const cssText = cssFile ? cssFile.text : ''
if (/tailwindcss|preflight|@theme|@layer/i.test(cssText) || /-webkit-text-size-adjust:\s*100%/i.test(cssText)) {
  throw new Error('Client CSS must remain scoped and must not bundle Tailwind or global resets')
}

const wrappedFactory = `window.__ModuleLoader__.load({
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
    var __TAVLO_HOOKS_CSS__ = ${JSON.stringify(cssText)};
    ${jsFile.text}
    return module.exports;
  },
});`

const finalBuild = await transform(wrappedFactory, {
  target: 'es2020',
  minifySyntax: true,
  minifyWhitespace: true,
  legalComments: 'inline',
})

for (const [, , importName] of finalBuild.code.matchAll(/\brequire\((['"])([^'"]+)\1\)/g)) {
  if (!runtimeModules.has(importName)) {
    throw new Error(`Unsupported runtime require in client bundle: ${importName}`)
  }
}

if (!finalBuild.code.includes('.tavlo-hooks-root')) {
  throw new Error('Expected scoped .tavlo-hooks-root CSS inside bundled client')
}

const packageDirs = new Set(
  Object.keys(result.metafile.inputs).flatMap((file) => {
    const match = file.match(/^(.*node_modules[/\\](?:@[^/\\]+[/\\])?[^/\\]+)[/\\]/)
    return match ? [match[1].replace(/\\/g, '/')] : []
  }),
)

const notices = [
  `${pkg.name}@${pkg.version}\nMIT License\nCopyright (c) Tavlo\nPermission is hereby granted, free of charge, to any person obtaining a copy of this software and associated documentation files (the "Software"), to deal in the Software without restriction, including without limitation the rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the Software, subject to the following conditions: The above copyright notice and this permission notice shall be included in all copies or substantial portions of the Software.`,
]

for (const dir of [...packageDirs].sort()) {
  const depPkg = JSON.parse(await read(`${dir}/package.json`))
  let notice
  for (const candidate of ['LICENSE', 'LICENSE.txt', 'LICENSE.md', 'LICENSE-MIT', 'license']) {
    try {
      notice = await read(`${dir}/${candidate}`)
      break
    } catch (error) {
      if (error.code !== 'ENOENT') throw error
    }
  }
  if (!notice) {
    notice = `${depPkg.license || 'See package metadata'}`
  }
  notices.push(`${depPkg.name}@${depPkg.version}\n${notice}`)
}

await mkdir(resolve(root, 'lib'), { recursive: true })
await writeFile(
  resolve(root, 'lib/client.js'),
  `// Generated by scripts/build-client.mjs. See client.js.LEGAL.txt for notices.\n${finalBuild.code}`,
)
await writeFile(resolve(root, 'lib/client.js.LEGAL.txt'), notices.join('\n\n') + '\n')

console.log(`Built lib/client.js (${finalBuild.code.length} bytes, css ${cssText.length} bytes)`)
